-- Readiness deduplicates successful receipts before joining the required checklist.
-- Conservative policy: BOTH business jobs wait for all eleven producers.
CREATE VIEW READINESS AS
WITH valid_receipts AS (
 SELECT DISTINCT PRODUCER,PROCESS_DATE,SOURCE_VERSION
 FROM RECEIPTS WHERE STATUS='SUCCESS' AND WATERMARK>=PROCESS_DATE
), parent_status AS (
 SELECT q.PROCESS_DATE,q.SOURCE_VERSION,
  SUM(IFF(r.PRODUCER IS NULL,1,0)) AS MISSING_PARENTS
 FROM REQUESTS q CROSS JOIN DEPENDENCIES d
 LEFT JOIN valid_receipts r ON r.PRODUCER=d.PRODUCER
  AND r.PROCESS_DATE=q.PROCESS_DATE AND r.SOURCE_VERSION=q.SOURCE_VERSION
 GROUP BY q.PROCESS_DATE,q.SOURCE_VERSION
), valid_files AS (
 SELECT DISTINCT PROCESS_DATE,SOURCE_VERSION FROM FILE_MANIFEST
 WHERE FILE_NAME='entities.csv' AND STATUS='SUCCESS' AND WATERMARK>=PROCESS_DATE
)
SELECT q.*,p.MISSING_PARENTS,(f.PROCESS_DATE IS NOT NULL) AS FILE_READY
FROM REQUESTS q JOIN parent_status p
 ON p.PROCESS_DATE=q.PROCESS_DATE AND p.SOURCE_VERSION=q.SOURCE_VERSION
LEFT JOIN valid_files f
 ON f.PROCESS_DATE=q.PROCESS_DATE AND f.SOURCE_VERSION=q.SOURCE_VERSION;
-- CHECKPOINT: dependency rows=11, distinct producers=11, writer rows=1.
SELECT COUNT(*) AS DEPENDENCIES,COUNT(DISTINCT PRODUCER) AS DISTINCT_PRODUCERS FROM DEPENDENCIES;
SELECT COUNT(*) AS WRITER_ROWS FROM WRITER_LOCK WHERE LOCK_ID=1;
SELECT COUNT(*) AS REQUESTS FROM REQUESTS; -- 0 before fixtures
