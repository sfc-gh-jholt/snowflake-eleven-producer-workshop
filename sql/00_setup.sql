-- Readiness uses EXISTS: duplicate receipts never replace a missing producer.
-- Conservative policy: BOTH business jobs wait for all eleven producers.
CREATE VIEW READINESS AS
SELECT q.*,
 (SELECT COUNT(*) FROM DEPENDENCIES d WHERE NOT EXISTS (
   SELECT 1 FROM RECEIPTS r WHERE r.PRODUCER=d.PRODUCER
   AND r.PROCESS_DATE=q.PROCESS_DATE AND r.SOURCE_VERSION=q.SOURCE_VERSION
   AND r.STATUS='SUCCESS' AND r.WATERMARK>=q.PROCESS_DATE)) AS MISSING_PARENTS,
 EXISTS(SELECT 1 FROM FILE_MANIFEST f WHERE f.PROCESS_DATE=q.PROCESS_DATE
   AND f.SOURCE_VERSION=q.SOURCE_VERSION AND f.FILE_NAME='entities.csv'
   AND f.STATUS='SUCCESS' AND f.WATERMARK>=q.PROCESS_DATE) AS FILE_READY
FROM REQUESTS q;