-- After deterministic tests, compare Jan 7 using a separate preparation path.
-- This replaces the eligibility SELECT, NOT the transactional publication contract.
USE DATABASE ELEVEN_PRODUCER_LAB;
USE WAREHOUSE ELEVEN_PRODUCER_WH;
CREATE SCHEMA DT_LAB;
USE SCHEMA DT_LAB;
CREATE TABLE INPUT_SNAPSHOT (
 PROCESS_DATE DATE,SOURCE_VERSION VARCHAR,ENTITY_ID NUMBER,
 REQUIREMENT_A BOOLEAN,REQUIREMENT_B BOOLEAN
) CHANGE_TRACKING=TRUE;
INSERT INTO INPUT_SNAPSHOT
SELECT PROCESS_DATE,SOURCE_VERSION,ENTITY_ID,REQUIREMENT_A,REQUIREMENT_B
FROM ELEVEN_PRODUCER_LAB.DEMO.SOURCE_ENTITIES
WHERE PROCESS_DATE='2025-01-07' AND SOURCE_VERSION='V1';
CREATE DYNAMIC TABLE PREPARED
 TARGET_LAG=DOWNSTREAM WAREHOUSE=ELEVEN_PRODUCER_WH
 REFRESH_MODE=INCREMENTAL INITIALIZE=ON_CREATE
AS SELECT PROCESS_DATE,SOURCE_VERSION,ENTITY_ID,
 REQUIREMENT_A AND REQUIREMENT_B AS ELIGIBLE
FROM ELEVEN_PRODUCER_LAB.DT_LAB.INPUT_SNAPSHOT;
-- DOWNSTREAM on a leaf is intentional here: manual refresh only, no timed polling.
SHOW DYNAMIC TABLES IN SCHEMA ELEVEN_PRODUCER_LAB.DT_LAB;
-- Expect PREPARED, INCREMENTAL. Initial result: 101 rows and 11 eligible.
SELECT COUNT(*) AS ROW_COUNT,COUNT_IF(ELIGIBLE) AS ELIGIBLE_COUNT FROM PREPARED;
CREATE TABLE FROZEN_CANDIDATE AS SELECT * FROM PREPARED;
-- Compare exact rows in BOTH directions; expect 0 differences.
WITH missing_rows AS (
 SELECT * FROM ELEVEN_PRODUCER_LAB.DEMO.CANDIDATES
 WHERE PROCESS_DATE='2025-01-07' AND SOURCE_VERSION='V1'
 MINUS SELECT * FROM FROZEN_CANDIDATE
), extra_rows AS (
 SELECT * FROM FROZEN_CANDIDATE MINUS
 SELECT * FROM ELEVEN_PRODUCER_LAB.DEMO.CANDIDATES
 WHERE PROCESS_DATE='2025-01-07' AND SOURCE_VERSION='V1'
)
SELECT (SELECT COUNT(*) FROM missing_rows)+(SELECT COUNT(*) FROM extra_rows) AS DIFFERENCES;
-- Teach freshness versus publication: changing source refreshes the DT but must
-- NOT silently change the approved immutable candidate or published business data.
UPDATE INPUT_SNAPSHOT SET REQUIREMENT_B=TRUE WHERE ENTITY_ID=11;
ALTER DYNAMIC TABLE PREPARED REFRESH;
SELECT COUNT(*) AS ROW_COUNT,COUNT_IF(ELIGIBLE) AS ELIGIBLE_COUNT FROM PREPARED; -- 101,12
SELECT COUNT(*) AS ROW_COUNT,COUNT_IF(ELIGIBLE) AS ELIGIBLE_COUNT FROM FROZEN_CANDIDATE; -- 101,11
-- Repair synthetic input; recheck original parity.
UPDATE INPUT_SNAPSHOT SET REQUIREMENT_B=FALSE WHERE ENTITY_ID=11;
ALTER DYNAMIC TABLE PREPARED REFRESH;
SELECT COUNT(*) AS ROW_COUNT,COUNT_IF(ELIGIBLE) AS ELIGIBLE_COUNT FROM PREPARED; -- 101,11
ALTER DYNAMIC TABLE PREPARED SUSPEND;
SHOW DYNAMIC TABLES IN SCHEMA ELEVEN_PRODUCER_LAB.DT_LAB; -- scheduling_state=SUSPENDED
USE SCHEMA DEMO;
