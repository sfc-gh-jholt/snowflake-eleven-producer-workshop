USE DATABASE ELEVEN_PRODUCER_LAB;
USE SCHEMA DEMO;
ALTER TASK CAPTURE_ROOT SUSPEND;
ALTER TASK WATCHDOG_TASK SUSPEND;
ALTER TASK INVENTORY_TASK SUSPEND;
ALTER TASK PUBLISH_TASK SUSPEND;
SHOW TASKS IN SCHEMA ELEVEN_PRODUCER_LAB.DEMO;
-- Disable optional DMF schedules even if no associations were installed.
ALTER VIEW CURRENT_ENTITIES SET DATA_METRIC_SCHEDULE = '';
SHOW PARAMETERS LIKE 'DATA_METRIC_SCHEDULE' IN TABLE CURRENT_ENTITIES;
-- CHECKPOINT: 4 tasks suspended; DATA_METRIC_SCHEDULE is empty.
-- If the DT comparison was installed, suspend its refreshes as well:
EXECUTE IMMEDIATE $$
DECLARE installed NUMBER;
BEGIN
 SELECT COUNT(*) INTO :installed FROM ELEVEN_PRODUCER_LAB.INFORMATION_SCHEMA.SCHEMATA
 WHERE SCHEMA_NAME='DT_LAB';
 IF(installed>0) THEN
  EXECUTE IMMEDIATE 'ALTER DYNAMIC TABLE IF EXISTS ELEVEN_PRODUCER_LAB.DT_LAB.PREPARED SUSPEND';
 END IF;
END; $$;
-- Suspension does not cancel a run already executing. Inspect task history.
WITH recent_runs AS (
 SELECT NAME,STATE,ERROR_MESSAGE,DATABASE_NAME,SCHEMA_NAME
 FROM TABLE(SNOWFLAKE.INFORMATION_SCHEMA.TASK_HISTORY(
  TASK_NAME=>'CAPTURE_ROOT',SCHEDULED_TIME_RANGE_START=>DATEADD('hour',-2,CURRENT_TIMESTAMP()),RESULT_LIMIT=>10000))
 UNION ALL
 SELECT NAME,STATE,ERROR_MESSAGE,DATABASE_NAME,SCHEMA_NAME
 FROM TABLE(SNOWFLAKE.INFORMATION_SCHEMA.TASK_HISTORY(
  TASK_NAME=>'INVENTORY_TASK',SCHEDULED_TIME_RANGE_START=>DATEADD('hour',-2,CURRENT_TIMESTAMP()),RESULT_LIMIT=>10000))
 UNION ALL
 SELECT NAME,STATE,ERROR_MESSAGE,DATABASE_NAME,SCHEMA_NAME
 FROM TABLE(SNOWFLAKE.INFORMATION_SCHEMA.TASK_HISTORY(
  TASK_NAME=>'PUBLISH_TASK',SCHEDULED_TIME_RANGE_START=>DATEADD('hour',-2,CURRENT_TIMESTAMP()),RESULT_LIMIT=>10000))
 UNION ALL
 SELECT NAME,STATE,ERROR_MESSAGE,DATABASE_NAME,SCHEMA_NAME
 FROM TABLE(SNOWFLAKE.INFORMATION_SCHEMA.TASK_HISTORY(
  TASK_NAME=>'WATCHDOG_TASK',SCHEDULED_TIME_RANGE_START=>DATEADD('hour',-2,CURRENT_TIMESTAMP()),RESULT_LIMIT=>10000))
)
SELECT NAME,STATE,ERROR_MESSAGE FROM recent_runs
WHERE DATABASE_NAME='ELEVEN_PRODUCER_LAB' AND SCHEMA_NAME='DEMO'
 AND STATE IN ('EXECUTING','SCHEDULED');
