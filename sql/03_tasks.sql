USE DATABASE ELEVEN_PRODUCER_LAB;
USE SCHEMA DEMO;
CREATE TASK CAPTURE_ROOT WAREHOUSE=ELEVEN_PRODUCER_WH
 USER_TASK_TIMEOUT_MS=120000 OVERLAP_POLICY=NO_OVERLAP
 TASK_AUTO_RETRY_ATTEMPTS=1 SUSPEND_TASK_AFTER_NUM_FAILURES=3
 WHEN SYSTEM$STREAM_HAS_DATA('ELEVEN_PRODUCER_LAB.DEMO.COMPLETION_STREAM')
 AS CALL CAPTURE_EVENTS(FALSE);
CREATE TASK INVENTORY_TASK WAREHOUSE=ELEVEN_PRODUCER_WH USER_TASK_TIMEOUT_MS=120000
 AFTER CAPTURE_ROOT AS CALL DRAIN_STAGE('INVENTORY');
CREATE TASK PUBLISH_TASK WAREHOUSE=ELEVEN_PRODUCER_WH USER_TASK_TIMEOUT_MS=120000
 AFTER INVENTORY_TASK AS CALL DRAIN_STAGE('PUBLISH');
CREATE TASK WATCHDOG_TASK WAREHOUSE=ELEVEN_PRODUCER_WH SCHEDULE='15 MINUTE'
 USER_TASK_TIMEOUT_MS=120000 SUSPEND_TASK_AFTER_NUM_FAILURES=3
 AS CALL WATCHDOG(CONVERT_TIMEZONE('America/New_York',CURRENT_TIMESTAMP())::TIMESTAMP_NTZ);
