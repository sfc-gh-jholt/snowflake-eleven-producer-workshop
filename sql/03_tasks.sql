USE DATABASE ELEVEN_PRODUCER_LAB;
USE SCHEMA DEMO;
CREATE TASK CAPTURE_ROOT WAREHOUSE=ELEVEN_PRODUCER_WH
 USER_TASK_TIMEOUT_MS=120000 OVERLAP_POLICY=NO_OVERLAP LOCK_TIMEOUT=60
 TASK_AUTO_RETRY_ATTEMPTS=1 SUSPEND_TASK_AFTER_NUM_FAILURES=3
 WHEN SYSTEM$STREAM_HAS_DATA('ELEVEN_PRODUCER_LAB.DEMO.COMPLETION_STREAM')
 AS CALL CAPTURE_EVENTS(FALSE);
CREATE TASK INVENTORY_TASK WAREHOUSE=ELEVEN_PRODUCER_WH USER_TASK_TIMEOUT_MS=120000 LOCK_TIMEOUT=60
 AFTER CAPTURE_ROOT AS CALL DRAIN_STAGE('INVENTORY');
CREATE TASK PUBLISH_TASK WAREHOUSE=ELEVEN_PRODUCER_WH USER_TASK_TIMEOUT_MS=120000 LOCK_TIMEOUT=60
 AFTER INVENTORY_TASK AS CALL DRAIN_STAGE('PUBLISH');
CREATE TASK WATCHDOG_TASK WAREHOUSE=ELEVEN_PRODUCER_WH SCHEDULE='15 MINUTE'
 USER_TASK_TIMEOUT_MS=120000 SUSPEND_TASK_AFTER_NUM_FAILURES=3 LOCK_TIMEOUT=60
 AS CALL WATCHDOG(CONVERT_TIMEZONE('America/New_York',CURRENT_TIMESTAMP())::TIMESTAMP_NTZ);
-- LOCK_TIMEOUT=60: a writer blocked on WRITER_LOCK fails fast instead of waiting 12 hours.
-- All four tasks remain SUSPENDED. Enable only after the deterministic tests.
SHOW TASKS IN SCHEMA ELEVEN_PRODUCER_LAB.DEMO; -- 4 rows, state=suspended
SELECT COUNT(*) AS COMPLETIONS FROM ELEVEN_PRODUCER_LAB.DEMO.COMPLETIONS; -- 0