CREATE PROCEDURE CAPTURE_EVENTS(P_INJECT_FAILURE BOOLEAN)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS $$
DECLARE tx BOOLEAN DEFAULT FALSE; captured NUMBER;
 injected EXCEPTION(-20001,'Injected capture failure');
BEGIN
 BEGIN TRANSACTION; tx:=TRUE;
 INSERT INTO RECEIPTS
 SELECT PRODUCER,PROCESS_DATE,SOURCE_VERSION,STATUS,WATERMARK,ROW_COUNT,CREATED_AT
 FROM COMPLETION_STREAM;
 captured:=SQLROWCOUNT;
 IF(P_INJECT_FAILURE) THEN RAISE injected; END IF;
 INSERT INTO CAPTURE_AUDIT(CAPTURED_ROWS) VALUES(:captured);
 COMMIT; tx:=FALSE;
 RETURN 'CAPTURED '||captured;
EXCEPTION WHEN OTHER THEN
 IF(tx) THEN ROLLBACK; END IF;
 RAISE;
END; $$;

CREATE PROCEDURE RUN_STAGE(P_DATE DATE,P_VERSION VARCHAR,P_JOB VARCHAR,P_INJECT_FAILURE BOOLEAN)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS $$
DECLARE
 tx BOOLEAN DEFAULT FALSE; records NUMBER; missing NUMBER; file_ok BOOLEAN;
 expected_rows NUMBER; expected_eligible NUMBER; observed NUMBER;
 check_name VARCHAR DEFAULT 'REQUEST'; expected NUMBER DEFAULT 0;
 message VARCHAR; quality_failed BOOLEAN DEFAULT FALSE;
 invalid EXCEPTION(-20002,'Invalid or unsupported request');
 bad_quality EXCEPTION(-20003,'Quality gate rejected publication; inspect QUALITY_RESULTS');
 injected EXCEPTION(-20004,'Injected failure after history expiration');
BEGIN
 IF(P_DATE IS NULL OR P_VERSION IS NULL OR P_JOB IS NULL
    OR P_JOB NOT IN ('INVENTORY','PUBLISH')) THEN RAISE invalid; END IF;
 BEGIN TRANSACTION; tx:=TRUE;
 -- Real UPDATE serialization, not an unenforced standard-table primary key.
 UPDATE WRITER_LOCK SET REVISION=REVISION+1 WHERE LOCK_ID=1;
 IF(SQLROWCOUNT<>1) THEN RAISE invalid; END IF;
 SELECT COUNT(*) INTO :records FROM REQUESTS
 WHERE PROCESS_DATE=:P_DATE AND SOURCE_VERSION=:P_VERSION;
 IF(records<>1) THEN RAISE invalid; END IF;
 SELECT COUNT(*) INTO :records FROM COMPLETIONS
 WHERE PROCESS_DATE=:P_DATE AND SOURCE_VERSION=:P_VERSION AND JOB=:P_JOB;
 IF(records>0) THEN COMMIT; tx:=FALSE; RETURN 'NOOP'; END IF;
 -- Reject alternate versions and backdated reconstruction, rather than guessing policy.
 SELECT COUNT(*) INTO :records FROM COMPLETIONS
 WHERE PROCESS_DATE>:P_DATE OR (PROCESS_DATE=:P_DATE AND SOURCE_VERSION<>:P_VERSION);
 IF(records>0) THEN RAISE invalid; END IF;
 SELECT COUNT(*) INTO :records FROM REQUESTS q WHERE q.PROCESS_DATE<:P_DATE
 AND NOT EXISTS(SELECT 1 FROM COMPLETIONS c WHERE c.PROCESS_DATE=q.PROCESS_DATE
 AND c.SOURCE_VERSION=q.SOURCE_VERSION AND c.JOB='PUBLISH');
 IF(records>0) THEN COMMIT; tx:=FALSE; RETURN 'WAIT_EARLIER_DATE'; END IF;
 SELECT COUNT(*) INTO :records FROM DEPENDENCIES;
 IF(records<>11) THEN RAISE invalid; END IF;
 SELECT COUNT(DISTINCT PRODUCER) INTO :records FROM DEPENDENCIES;
 IF(records<>11) THEN RAISE invalid; END IF;
 SELECT MISSING_PARENTS,FILE_READY,EXPECTED_ROWS,EXPECTED_ELIGIBLE
 INTO :missing,:file_ok,:expected_rows,:expected_eligible FROM READINESS
 WHERE PROCESS_DATE=:P_DATE AND SOURCE_VERSION=:P_VERSION;
 IF(missing>0 OR NOT file_ok) THEN COMMIT; tx:=FALSE; RETURN 'WAIT'; END IF;

 IF(P_JOB='INVENTORY') THEN
  -- Snapshot once: publication uses this candidate, not a later mutable source read.
  DELETE FROM CANDIDATES WHERE PROCESS_DATE=:P_DATE AND SOURCE_VERSION=:P_VERSION;
  INSERT INTO CANDIDATES
  SELECT PROCESS_DATE,SOURCE_VERSION,ENTITY_ID,REQUIREMENT_A AND REQUIREMENT_B
  FROM SOURCE_ENTITIES WHERE PROCESS_DATE=:P_DATE AND SOURCE_VERSION=:P_VERSION;
 ELSE
  SELECT COUNT(*) INTO :records FROM COMPLETIONS WHERE PROCESS_DATE=:P_DATE
  AND SOURCE_VERSION=:P_VERSION AND JOB='INVENTORY';
  IF(records<>1) THEN COMMIT; tx:=FALSE; RETURN 'WAIT_INVENTORY'; END IF;
 END IF;

 -- Synchronous batch-specific checks run under the same writer lock as the writes.
 -- Candidate rows must not be writable by unrelated production roles.
 check_name:='NULL_KEYS_OR_STATUS'; expected:=0;
 SELECT COUNT(*) INTO :observed FROM CANDIDATES
 WHERE PROCESS_DATE=:P_DATE AND SOURCE_VERSION=:P_VERSION
 AND (ENTITY_ID IS NULL OR ELIGIBLE IS NULL);
 IF(observed<>expected) THEN quality_failed:=TRUE; RAISE bad_quality; END IF;
 INSERT INTO QUALITY_RESULTS(PROCESS_DATE,SOURCE_VERSION,JOB,CHECK_NAME,OBSERVED,EXPECTED,PASSED)
 VALUES(:P_DATE,:P_VERSION,:P_JOB,:check_name,:observed,:expected,TRUE);

 check_name:='DUPLICATE_KEYS';
 SELECT COUNT(*)-COUNT(DISTINCT ENTITY_ID) INTO :observed FROM CANDIDATES
 WHERE PROCESS_DATE=:P_DATE AND SOURCE_VERSION=:P_VERSION;
 IF(observed<>expected) THEN quality_failed:=TRUE; RAISE bad_quality; END IF;
 INSERT INTO QUALITY_RESULTS(PROCESS_DATE,SOURCE_VERSION,JOB,CHECK_NAME,OBSERVED,EXPECTED,PASSED)
 VALUES(:P_DATE,:P_VERSION,:P_JOB,:check_name,:observed,:expected,TRUE);

 check_name:='ROW_COUNT'; expected:=expected_rows;
 SELECT COUNT(*) INTO :observed FROM CANDIDATES
 WHERE PROCESS_DATE=:P_DATE AND SOURCE_VERSION=:P_VERSION;
 IF(expected IS NULL OR observed<>expected) THEN quality_failed:=TRUE; RAISE bad_quality; END IF;
 INSERT INTO QUALITY_RESULTS(PROCESS_DATE,SOURCE_VERSION,JOB,CHECK_NAME,OBSERVED,EXPECTED,PASSED)
 VALUES(:P_DATE,:P_VERSION,:P_JOB,:check_name,:observed,:expected,TRUE);

 check_name:='ELIGIBLE_TOTAL'; expected:=expected_eligible;
 SELECT COALESCE(COUNT_IF(ELIGIBLE),0) INTO :observed FROM CANDIDATES
 WHERE PROCESS_DATE=:P_DATE AND SOURCE_VERSION=:P_VERSION;
 IF(expected IS NULL OR observed<>expected) THEN quality_failed:=TRUE; RAISE bad_quality; END IF;
 INSERT INTO QUALITY_RESULTS(PROCESS_DATE,SOURCE_VERSION,JOB,CHECK_NAME,OBSERVED,EXPECTED,PASSED)
 VALUES(:P_DATE,:P_VERSION,:P_JOB,:check_name,:observed,:expected,TRUE);

 IF(P_JOB='INVENTORY') THEN
  MERGE INTO INVENTORY t USING (SELECT ENTITY_ID FROM CANDIDATES
   WHERE PROCESS_DATE=:P_DATE AND SOURCE_VERSION=:P_VERSION) s ON t.ENTITY_ID=s.ENTITY_ID
  WHEN MATCHED THEN UPDATE SET DAY_COUNT=t.DAY_COUNT+1
  WHEN NOT MATCHED THEN INSERT(ENTITY_ID,DAY_COUNT) VALUES(s.ENTITY_ID,1);
 ELSE
  DELETE FROM WORKSET;
  INSERT INTO WORKSET
  SELECT s.ENTITY_ID,s.ELIGIBLE FROM CANDIDATES s LEFT JOIN HISTORY h
  ON h.ENTITY_ID=s.ENTITY_ID AND h.VALID_TO IS NULL
  WHERE s.PROCESS_DATE=:P_DATE AND s.SOURCE_VERSION=:P_VERSION
  AND (h.ENTITY_ID IS NULL OR h.ELIGIBLE IS DISTINCT FROM s.ELIGIBLE);
  UPDATE HISTORY SET VALID_TO=:P_DATE
  WHERE VALID_TO IS NULL AND ENTITY_ID IN (SELECT ENTITY_ID FROM WORKSET);
  IF(P_INJECT_FAILURE) THEN RAISE injected; END IF;
  INSERT INTO HISTORY SELECT ENTITY_ID,ELIGIBLE,:P_DATE,NULL FROM WORKSET;
  check_name:='HISTORY_INVARIANTS'; expected:=0;
  SELECT COUNT(*) INTO :observed FROM (
   SELECT ENTITY_ID FROM HISTORY WHERE VALID_TO IS NULL GROUP BY ENTITY_ID HAVING COUNT(*)>1
   UNION ALL
   SELECT ENTITY_ID FROM HISTORY WHERE VALID_TO<=VALID_FROM
   UNION ALL
   SELECT ENTITY_ID FROM (
    SELECT ENTITY_ID,VALID_FROM,ROW_NUMBER() OVER(PARTITION BY ENTITY_ID ORDER BY VALID_FROM) AS RN,
     LAG(VALID_TO) OVER(PARTITION BY ENTITY_ID ORDER BY VALID_FROM) AS PREVIOUS_END
    FROM HISTORY)
   WHERE RN>1 AND (PREVIOUS_END IS NULL OR PREVIOUS_END>VALID_FROM)
  );
  IF(observed<>0) THEN quality_failed:=TRUE; RAISE bad_quality; END IF;
  INSERT INTO QUALITY_RESULTS(PROCESS_DATE,SOURCE_VERSION,JOB,CHECK_NAME,OBSERVED,EXPECTED,PASSED)
  VALUES(:P_DATE,:P_VERSION,:P_JOB,:check_name,:observed,:expected,TRUE);
 END IF;
 INSERT INTO COMPLETIONS(PROCESS_DATE,SOURCE_VERSION,JOB) VALUES(:P_DATE,:P_VERSION,:P_JOB);
 COMMIT; tx:=FALSE; RETURN 'COMMITTED';
EXCEPTION WHEN OTHER THEN
 message:=SQLERRM;
 IF(tx) THEN ROLLBACK; END IF;
 -- Persist the failed check AFTER rollback; a success receipt cannot escape rollback.
 IF(quality_failed) THEN
  INSERT INTO QUALITY_RESULTS(PROCESS_DATE,SOURCE_VERSION,JOB,CHECK_NAME,OBSERVED,EXPECTED,PASSED)
  VALUES(:P_DATE,:P_VERSION,:P_JOB,:check_name,:observed,:expected,FALSE);
 END IF;
 INSERT INTO FAILURES(PROCESS_DATE,SOURCE_VERSION,JOB,MESSAGE)
 VALUES(:P_DATE,:P_VERSION,:P_JOB,:message);
 RAISE;
END; $$;

CREATE PROCEDURE DRAIN_STAGE(P_JOB VARCHAR)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS $$
DECLARE requests_cursor CURSOR FOR
 SELECT PROCESS_DATE,SOURCE_VERSION FROM REQUESTS ORDER BY PROCESS_DATE,SOURCE_VERSION;
 business_date DATE; version_name VARCHAR; outcome VARCHAR;
BEGIN
 -- NO outer transaction: each RUN_STAGE owns its transaction and writer lock.
 FOR request IN requests_cursor DO
  business_date:=request.PROCESS_DATE; version_name:=request.SOURCE_VERSION;
  CALL RUN_STAGE(:business_date,:version_name,:P_JOB,FALSE) INTO :outcome;
 END FOR;
 RETURN 'DONE';
END; $$;

CREATE PROCEDURE WATCHDOG(P_NOW TIMESTAMP_NTZ)
RETURNS VARCHAR LANGUAGE SQL EXECUTE AS OWNER AS $$
DECLARE tx BOOLEAN DEFAULT FALSE;
 invalid EXCEPTION(-20002,'Missing writer-control row or watchdog timestamp');
BEGIN
 IF(P_NOW IS NULL) THEN RAISE invalid; END IF;
 -- Log overdue work BEFORE trying recovery, so a poisoned batch cannot suppress it.
 BEGIN TRANSACTION; tx:=TRUE;
 UPDATE WRITER_LOCK SET REVISION=REVISION+1 WHERE LOCK_ID=1;
 IF(SQLROWCOUNT<>1) THEN RAISE invalid; END IF;
 INSERT INTO WARNINGS(PROCESS_DATE,SOURCE_VERSION,MESSAGE)
 SELECT q.PROCESS_DATE,q.SOURCE_VERSION,'Expected publication is overdue'
 FROM REQUESTS q WHERE q.DEADLINE<=:P_NOW
 AND NOT EXISTS(SELECT 1 FROM COMPLETIONS c WHERE c.PROCESS_DATE=q.PROCESS_DATE
  AND c.SOURCE_VERSION=q.SOURCE_VERSION AND c.JOB='PUBLISH')
 AND NOT EXISTS(SELECT 1 FROM WARNINGS w WHERE w.PROCESS_DATE=q.PROCESS_DATE
  AND w.SOURCE_VERSION=q.SOURCE_VERSION);
 COMMIT; tx:=FALSE;
 CALL CAPTURE_EVENTS(FALSE);
 CALL DRAIN_STAGE('INVENTORY');
 CALL DRAIN_STAGE('PUBLISH');
 RETURN 'CHECKED';
EXCEPTION WHEN OTHER THEN IF(tx) THEN ROLLBACK; END IF; RAISE;
END; $$;
