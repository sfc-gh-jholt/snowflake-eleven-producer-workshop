CREATE SCHEMA WARMUP;
USE SCHEMA WARMUP;
CREATE TABLE REQUIRED_PRODUCERS (PRODUCER VARCHAR);
INSERT INTO REQUIRED_PRODUCERS VALUES ('A'),('B');
CREATE TABLE RECEIPTS (PRODUCER VARCHAR,BUSINESS_DATE DATE);
CREATE TABLE INPUT_ROWS (ENTITY_ID NUMBER,AMOUNT NUMBER);
INSERT INTO INPUT_ROWS VALUES (1,10),(2,20);
CREATE TABLE PUBLISHED (ENTITY_ID NUMBER,AMOUNT NUMBER);
CREATE TABLE COMPLETIONS (BUSINESS_DATE DATE);
CREATE PROCEDURE TRY_PUBLISH(P_DATE DATE)
RETURNS VARCHAR LANGUAGE SQL AS $$
DECLARE missing NUMBER; completed NUMBER;
BEGIN
 SELECT COUNT(*) INTO :completed FROM COMPLETIONS WHERE BUSINESS_DATE=:P_DATE;
 IF(completed>0) THEN RETURN 'NOOP'; END IF;
 SELECT COUNT(*) INTO :missing FROM REQUIRED_PRODUCERS p
 WHERE NOT EXISTS(SELECT 1 FROM RECEIPTS r
  WHERE r.PRODUCER=p.PRODUCER AND r.BUSINESS_DATE=:P_DATE);
 IF(missing>0) THEN RETURN 'WAIT'; END IF;
 BEGIN TRANSACTION;
 INSERT INTO PUBLISHED SELECT ENTITY_ID,AMOUNT FROM INPUT_ROWS;
 INSERT INTO COMPLETIONS VALUES(:P_DATE);
 COMMIT;
 RETURN 'COMMITTED';
END; $$;
-- Predict before each CALL; select one section at a time for teaching.
CALL TRY_PUBLISH('2025-01-06'); -- WAIT: neither producer finished.
INSERT INTO RECEIPTS VALUES ('A','2025-01-06'),('A','2025-01-06');
CALL TRY_PUBLISH('2025-01-06'); -- WAIT: duplicates do not replace B.
SELECT COUNT(*) AS PUBLISHED_ROWS FROM PUBLISHED; -- 0
INSERT INTO RECEIPTS VALUES ('B','2025-01-06');
CALL TRY_PUBLISH('2025-01-06'); -- COMMITTED
CALL TRY_PUBLISH('2025-01-06'); -- NOOP
SELECT COUNT(*) AS PUBLISHED_ROWS,SUM(AMOUNT) AS TOTAL FROM PUBLISHED; -- 2, 30
SELECT COUNT(*) AS COMPLETIONS FROM COMPLETIONS; -- 1
